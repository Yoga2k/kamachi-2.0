class CodeGenerator:
    """Generates code snippets/scripts from natural language descriptions."""

    _instance = None

    def __new__(cls):
        if cls._instance is None:
            cls._instance = super(CodeGenerator, cls).__new__(cls)
            cls._instance._initialized = False
        return cls._instance

    def __init__(self):
        if getattr(self, "_initialized", False):
            return
        self._initialized = True
        GENERATED_CODE_DIR.mkdir(parents=True, exist_ok=True)
        self.memory = get_memory_store()
        self.gemini = get_gemini_client()

    def _detect_language_and_extension(self, query: str) -> tuple[str, str]:
        q = query.lower()
        if any(w in q for w in ["html", "web page", "login page", "landing page"]):
            return "html", ".html"
        if any(w in q for w in ["javascript", "js", "node"]):
            return "javascript", ".js"
        if any(w in q for w in ["sql", "database query"]):
            return "sql", ".sql"
        if any(w in q for w in ["c++", "cpp"]):
            return "cpp", ".cpp"
        return "python", ".py"

    def _extract_topic(self, query: str) -> str:
        t = query.lower().strip()
        for prefix in [
            "write a python script for",
            "write python script for",
            "write a python program for",
            "write python code for",
            "write a script for",
            "write code for",
            "generate code for",
            "generate a python script for",
            "create a python script for",
            "generate",
            "write",
        ]:
            if t.startswith(prefix):
                t = t[len(prefix):].strip()
                break
        t = re.sub(r"\bin\s+(?:python|javascript|js|html|c\+\+|sql)\b", "", t).strip()
        return t or "script"

    def generate_code(self, prompt: str, open_in_vscode: bool = False) -> Dict[str, Any]:
        """
        Generates code from prompt, writes it to storage/generated_code/, and records in memory.
        """
        GENERATED_CODE_DIR.mkdir(parents=True, exist_ok=True)
        topic = self._extract_topic(prompt)
        lang, ext = self._detect_language_and_extension(prompt)

        # 1. Check built-in templates first or as fallback
        code_content: Optional[str] = None
        for key, tpl in BUILTIN_TEMPLATES.items():
            if key in prompt.lower():
                code_content = tpl["code"]
                lang = tpl["lang"]
                ext = tpl["ext"]
                break

        # 2. Try Gemini API if not matched or if API key is present
        if not code_content:
            ai_prompt = (
                f"Write clean, runnable, well-commented {lang} code for: {topic}. "
                "Output ONLY the raw code without markdown backticks."
            )
            ai_reply = self.gemini.query_gemini_api(
                ai_prompt,
                system_prompt="You are an expert software engineer. Return only executable code.",
                max_tokens=800,
            )
            if ai_reply:
                # Strip markdown code fences if present
                cleaned = re.sub(r"^```[a-zA-Z]*\n", "", ai_reply.strip())
                cleaned = re.sub(r"\n```$", "", cleaned.strip())
                code_content = cleaned

        # 3. Generic clean template fallback if offline and not in BUILTIN_TEMPLATES
        if not code_content:
            safe_title = topic.replace('"', "'")
            if ext == ".py":
                code_content = f'''"""
{safe_title.title()} — Auto-generated Python Script by KAMACHI 2.0
Created: {datetime.now().strftime("%Y-%m-%d %H:%M:%S")}
"""

def main():
    print("Running {safe_title}...")
    # TODO: Implement custom logic for {safe_title}


if __name__ == "__main__":
    main()
'''
            elif ext == ".js":
                code_content = f"// {safe_title} — Generated by KAMACHI 2.0\nconsole.log('Running {safe_title}');\n"
            else:
                code_content = f"<!-- {safe_title} -->\n<h1>{safe_title.title()}</h1>\n"

        # 4. Save file
        slug = re.sub(r"[^a-z0-9]+", "_", topic.lower()).strip("_")[:30] or "generated_script"
        filename = f"{slug}{ext}"
        file_path = GENERATED_CODE_DIR / filename

        with open(file_path, "w", encoding="utf-8") as f:
            f.write(code_content)

        # 5. Record in work history
        self.memory.record_work(
            app_name="VS Code",
            file_path=str(file_path),
            project_dir=str(GENERATED_CODE_DIR),
            notes=f"Voice generated {lang} code for {topic}",
        )

        if open_in_vscode:
            try:
                subprocess.Popen(f'code "{file_path}"', shell=True)
            except Exception:
                pass

        speak(f"I have generated the {lang} code for {topic} and saved it as {filename}.")
        return {
            "status": f"Generated {filename}",
            "file_path": str(file_path),
            "language": lang,
            "topic": topic,
            "code": code_content,
        }

    def handle_command(self, command: str) -> str:
        open_vs = "vs code" in command.lower() or "vscode" in command.lower()
        res = self.generate_code(command, open_in_vscode=open_vs)
        return f"{res['status']} at {res['file_path']}"


def get_code_generator() -> CodeGenerator:
    return CodeGenerator()

